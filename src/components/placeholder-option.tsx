import type { ReactNode } from "react";

/**
 * Подсказка обязательного выбора в `<select>` — «Выберите счёт».
 *
 * Не значение, а приглашение: видна в закрытом поле, пока ничего не выбрано,
 * приглушена (`globals.css`, `data-placeholder`), а в раскрытом списке её нет —
 * `hidden` прячет её там, где браузер это умеет, `disabled` не даёт выбрать
 * там, где нет (Safari). До 27.09.2026 это был обычный пункт: «Выберите счёт»
 * стоял в списке первым наравне с «Кассой», выбирался, и форма отказывала уже
 * при записи, а в правилах и разборе выписки выбор пустоты запускал действие.
 *
 * У необязательного поля пустое — настоящее значение («Без категории», «Все
 * счета»): там обычный `<option value="">`.
 */
export function PlaceholderOption({ children }: { children: ReactNode }) {
  return (
    <option value="" disabled hidden data-placeholder="">
      {children}
    </option>
  );
}
